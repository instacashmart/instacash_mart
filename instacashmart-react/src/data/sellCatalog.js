const QUOTE_BONUS = 1000;

export function variantMultiplier(t, e, s) {
  const n = variantOptions[t] || {};
  let a = 1;
  if (n.storage) {
    a *= 1 + (e - n.storage.def) * n.storage.step;
  }
  if (n.ram) {
    a *= 1 + (s - n.ram.def) * n.ram.step;
  }
  return Math.max(a, 0.6);
}

export const calculateQuote = (t, e, s, n) => Math.round((t * e * s + n + QUOTE_BONUS) / 50) * 50;

export function findModel(t, e, s) {
  const n = String(e || "").toLowerCase();
  const a = Object.keys(deviceCatalog).sort((r, o) => (o === s) - (r === s));
  for (const r of [true, false]) {
    for (const category of a) {
      const l = deviceCatalog[category].models[t] || [];
      const index = l.findIndex((item) =>
        r ? item.name.toLowerCase() === n : item.name.toLowerCase().includes(n),
      );
      if (index >= 0) {
        return {
          category,
          brand: t,
          index,
          model: l[index],
        };
      }
    }
  }
  return null;
}

export function searchModels(t) {
  const e = t.toLowerCase().trim();
  const s = [];
  for (const n of Object.values(deviceCatalog)) {
    for (const [a, r] of Object.entries(n.models)) {
      for (const o of r) {
        if (o.name.toLowerCase().includes(e)) {
          s.push({
            brand: a,
            name: o.name,
            price: o.base + QUOTE_BONUS,
          });
        }
      }
    }
  }
  return s;
}
